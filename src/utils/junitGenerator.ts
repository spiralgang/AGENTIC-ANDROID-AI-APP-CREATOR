export function generateJUnitTest(filename: string, javaContent: string): { testPath: string; testContent: string; methods: string[] } {
  // Extract package name
  const packageMatch = javaContent.match(/package\s+([\w\.]+);/);
  const pkg = packageMatch ? packageMatch[1] : "com.example.app";
  
  // Extract class name
  const classMatch = javaContent.match(/public\s+class\s+(\w+)/);
  const className = classMatch ? classMatch[1] : filename.replace(".java", "");
  
  // Extract methods: search for standard method definitions with simple regex
  const methodRegex = /(?:public|protected|private|static)\s+[\w<>]+\s+(\w+)\s*\(/g;
  const methods: string[] = [];
  let match;
  while ((match = methodRegex.exec(javaContent)) !== null) {
    const mName = match[1];
    if (!["onCreate", "onDestroy", "onStart", "onResume", "onPause", "onStop", "toString", "equals"].includes(mName) && !methods.includes(mName)) {
      methods.push(mName);
    }
  }

  // Fallback if no methods are extracted
  if (methods.length === 0) {
    methods.push("testAppWorkflowInitialization");
    methods.push("testLocalStateEncryptionValidity");
  }

  // Define test class name
  const testClassName = `${className}Test`;
  const testPath = `app/src/test/java/${pkg.replace(/\./g, "/")}/${testClassName}.java`;

  let testContent = `package ${pkg};

import org.junit.Before;
import org.junit.Test;
import static org.junit.Assert.*;
import org.mockito.Mockito;
import static org.mockito.Mockito.*;

/**
 * Automated JUnit suite generated by JUnit Mock Testing Bot
 * Target Class Under Test: ${className}
 */
public class ${testClassName} {

    private ${className} classUnderTest;

    @Before
    public void setUp() throws Exception {
        // Automatically inject mocks or scaffold classes before each test run
        classUnderTest = mock(${className}.class);
    }
`;

  methods.forEach((m) => {
    testContent += `
    @Test
    public void test_${m}_AutonomousVerify() {
        // Arrange state conditions
        // Act - Invoke under test
        classUnderTest.${m}();
        
        // Assert mock interaction trace checks
        verify(classUnderTest, atLeastOnce()).${m}();
    }
`;
  });

  testContent += `
    @Test
    public void testCoherenceConsistency() {
        assertNotNull("Verify AST class scaffold holds correct instances", classUnderTest);
    }
}
`;

  return { testPath, testContent, methods };
}
